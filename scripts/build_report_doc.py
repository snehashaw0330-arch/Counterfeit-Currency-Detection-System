def table(doc, headers, rows):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_ALIGN_PARAGRAPH.CENTER
    for i, htext in enumerate(headers):
        run = t.rows[0].cells[i].paragraphs[0].add_run(htext)
        run.bold = True
    for row in rows:
        cells = t.add_row().cells
        for i, val in enumerate(row):
            cells[i].text = str(val)
    doc.add_paragraph().paragraph_format.space_after = Pt(6)
    return t


def code_block(doc, source_path, max_lines=400):
    try:
        text = source_path.read_text(encoding="utf-8")
    except Exception:
        body(doc, f"(source unavailable: {source_path.name})")
        return
    lines = text.splitlines()
    truncated = len(lines) > max_lines
    for line in lines[:max_lines]:
        p = doc.add_paragraph()
        pf = p.paragraph_format
        pf.space_after = Pt(0)
        pf.space_before = Pt(0)
        pf.line_spacing = 1.0
        _shade(p)
        r = p.add_run(line if line else " ")
        r.font.name = "Consolas"
        r.font.size = Pt(9)
    if truncated:
        body(doc, f"... (listing shortened to {max_lines} lines; the full "
                  f"{len(lines)}-line source is in {source_path.name}).")


