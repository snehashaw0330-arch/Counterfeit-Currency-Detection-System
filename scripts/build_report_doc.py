def _roc_fallback():
    """Operating-point ROC (one real test point per model) when the
    precomputed curves are unavailable. Derived from the saved confusion
    matrices; positive class = genuine."""
    labels = [("svm_rbf", "SVM (RBF)"), ("random_forest", "Random Forest"),
              ("logistic_regression", "Logistic Regression"), ("knn", "KNN")]
    out = []
    try:
        models = json.loads(
            (ROOT / "models" / "classical" / "metrics.json")
            .read_text(encoding="utf-8"))["models"]
    except Exception:
        models = {}
    for key, lab in labels:
        m = models.get(key)
        if not m:
            continue
        cm = m["confusion_matrix"]          # [[TN, FP], [FN, TP]]
        tpr = cm[1][1] / max(cm[1][0] + cm[1][1], 1)
        fpr = cm[0][1] / max(cm[0][0] + cm[0][1], 1)
        out.append({"label": lab, "fpr": [0.0, fpr, 1.0], "tpr": [0.0, tpr, 1.0],
                    "auc": round((tpr + (1 - fpr)) / 2, 4)})
    # CNN operating point (BENCHMARK.md: fake[3,3] / genuine[4,7]).
    out.append({"label": "MobileNetV2 (CNN)", "fpr": [0.0, 0.5, 1.0],
                "tpr": [0.0, 0.6364, 1.0], "auc": 0.5682})
    return out


def _roc_data():
    """Real ROC curves from scripts/compute_roc.py if present, else the
    operating-point fallback. Returns a list of {label, fpr, tpr, auc}."""
    p = GEN / "roc_data.json"
    if p.exists():
        try:
            curves = json.loads(p.read_text(encoding="utf-8"))["curves"]
            return [{"label": c["label"], "fpr": c["fpr"], "tpr": c["tpr"],
                     "auc": c["auc"]} for c in curves.values()]
        except Exception:
            pass
    return _roc_fallback()


def fig_roc(path):
    """ROC curve per ML technique, drawn from the real test-set probabilities
    computed by scripts/compute_roc.py. Best AUC is listed first."""
    from PIL import Image, ImageDraw
    items = sorted(_roc_data(), key=lambda c: -c["auc"])
    W, H = 1360, 980
    img = Image.new("RGB", (W, H), "white")
    d = ImageDraw.Draw(img)
    ax0, ay0, ax1, ay1 = 150, 120, 860, 830
    gf = _font(20)

    def X(v):
        return ax0 + v * (ax1 - ax0)

    def Y(v):
        return ay1 - v * (ay1 - ay0)

    for t in range(0, 11, 2):
        v = t / 10
        d.line([X(v), ay0, X(v), ay1], fill=(232, 235, 237), width=1)
        d.line([ax0, Y(v), ax1, Y(v)], fill=(232, 235, 237), width=1)
