_FONT_CACHE = {}


def _font(size, bold=False):
    key = (size, bold)
    if key in _FONT_CACHE:
        return _FONT_CACHE[key]
    from PIL import ImageFont
    candidates = (["arialbd.ttf", "Arial Bold.ttf"] if bold
                  else ["arial.ttf", "Arial.ttf"])
    f = None
    for name in candidates:
        try:
            f = ImageFont.truetype(name, size)
            break
        except Exception:
            continue
    if f is None:
        f = ImageFont.load_default()
    _FONT_CACHE[key] = f
    return f


def _text_center(d, cx, y, text, font, fill):
    w = d.textlength(text, font=font)
    d.text((cx - w / 2, y), text, font=font, fill=fill)


def _box(d, x0, y0, x1, y1, header, items, header_color=C_TEAL, fill=C_LIGHT,
         hsize=30, isize=23, radius=18):
    # drop shadow
    d.rounded_rectangle([x0 + 7, y0 + 7, x1 + 7, y1 + 7], radius=radius,
                        fill=C_SHADOW)
    d.rounded_rectangle([x0, y0, x1, y1], radius=radius, fill=fill,
                        outline=header_color, width=3)
    cx = (x0 + x1) / 2
    hf = _font(hsize, True)
    _text_center(d, cx, y0 + 14, header, hf, header_color)
    if items:
        d.line([x0 + 18, y0 + 14 + hsize + 12, x1 - 18, y0 + 14 + hsize + 12],
               fill=header_color, width=2)
    iy = y0 + 14 + hsize + 22
    itf = _font(isize)
    for it in items:
        d.text((x0 + 30, iy), "•  " + it, font=itf, fill=C_TX)
        iy += isize + 11


def _arrow_down(d, cx, y0, y1, color=C_ARROW, width=4):
    d.line([cx, y0, cx, y1], fill=color, width=width)
    d.polygon([(cx - 9, y1 - 14), (cx + 9, y1 - 14), (cx, y1)], fill=color)


def _arrow_h(d, x0, x1, cy, color=C_ARROW, width=4):
    d.line([x0, cy, x1, cy], fill=color, width=width)
    d.polygon([(x1 - 14, cy - 9), (x1 - 14, cy + 9), (x1, cy)], fill=color)


def fig_vflow(path, steps, title=None, header_color=C_TEAL, start_end=False):
    """Vertical stack of boxes joined by down-arrows. steps: [(header,[items])]."""
    from PIL import Image, ImageDraw
    W = 1400
    margin = 90
    top = 50
    gap = 50
    line_h = 34
    bw = W - 2 * margin

    heights = [70 + len(items) * line_h + (16 if items else 0)
               for _, items in steps]
    circle = 60 if start_end else 0
    total = top + circle + sum(heights) + gap * (len(steps) - 1) + circle + top
    if start_end:
        total += gap * 2

    img = Image.new("RGB", (W, total), "white")
    d = ImageDraw.Draw(img)
    cx = W / 2
    y = top

    if start_end:
        d.ellipse([cx - 16, y, cx + 16, y + 32], fill=(40, 40, 40))
        y += 32
        _arrow_down(d, cx, y, y + gap)
        y += gap

    spans = []
    for header, items in steps:
        bh = 70 + len(items) * line_h + (16 if items else 0)
        _box(d, margin, y, margin + bw, y + bh, header, items,
             header_color=header_color)
        spans.append((y, y + bh))
        y += bh
        if (header, items) != steps[-1] or start_end:
            _arrow_down(d, cx, y, y + gap)
            y += gap

    if start_end:
        d.ellipse([cx - 18, y, cx + 18, y + 36], outline=(40, 40, 40), width=4)
        d.ellipse([cx - 9, y + 9, cx + 9, y + 27], fill=(40, 40, 40))
        y += 36

    img.crop((0, 0, W, min(total, y + top))).save(path)


